const historyLayout = fs.readFileSync('app/history/layout.tsx', 'utf8')

// 1. Application Digital Twin must combine multiple evidence types rather than be a static form.
assert.match(twin, /buildStudentIntelligence/)
assert.match(twin, /deriveTwin/)
