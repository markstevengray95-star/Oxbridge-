const assert = require('node:assert/strict')
const fs = require('node:fs')

const twin = fs.readFileSync('components/application/application-digital-twin-dashboard.tsx', 'utf8')
const twinPage = fs.readFileSync('app/digital-twin/page.tsx', 'utf8')
const defence = fs.readFileSync('app/written-work-interview/page.tsx', 'utf8')
