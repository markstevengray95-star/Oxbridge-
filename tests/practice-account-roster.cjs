const assert = require("node:assert/strict")
const fs = require("node:fs")
const read = path => fs.readFileSync(path,"utf8")

const adminPage = read("app/admin/page.tsx")
const accountApi = read("app/api/admin/practice-accounts/route.ts")
const trackingApi = read("app/api/admin/practice-tracking/route.ts")
const loginApi = read("app/api/auth/practice-login/route.ts")

assert.match(adminPage,/getAppAdminAccess\(userId, email\)/)
assert.match(adminPage,/if \(!access\.isAdmin\) redirect\(/)
assert.match(adminPage,/\.from\("practice_access_accounts"\)/)
assert.match(adminPage,/Existing practice usernames/)
assert.match(adminPage,/practiceLogins\.map\(account/)
assert.match(adminPage,/href="\/admin\/practice-access"/)
assert.match(adminPage,/href="\/admin\/practice-tracking"/)
assert.match(accountApi,/getAppAdminAccess\(userId, email\)/)
assert.match(accountApi,/\.from\("practice_access_accounts"\)/)
assert.match(trackingApi,/authenticateAdmin\(\)/)
assert.match(trackingApi,/getAppAdminAccess\(userId, email\)/)
assert.match(trackingApi,/\.from\("practice_access_accounts"\)/)
assert.ok(!trackingApi.includes('.eq("created_by", auth.userId)'),"Old creator filter must not hide usernames from other platform admins")
assert.match(loginApi,/\.eq\("username_normalized", username\)/)
assert.match(loginApi,/signInWithPassword/)
console.log("PASS: existing practice usernames appear in main Admin and Practice Tracking without changing credentials.")
