assert.ok(adminApi.includes("school_staff_roles"),"Teacher's role must be server verified")
assert.ok(adminApi.includes('app_metadata:{account_type:"practice"'),"Managed teachers must be able to use existing username login")
assert.ok(adminApi.includes("oxbridge_join_school_seat"),"School attachments must use atomic seat admission RPC")
assert.ok(adminApi.includes('account_type!=="student"'),"Existing practice student account must be verified before school linking")
assert.ok(adminApi.includes("school_teacher_student_links"),"Teacher assignment must be school-specific")
