const assert = require("node:assert/strict")
const fs = require("node:fs")

const read = file => fs.readFileSync(file,"utf8")
const scope = read("lib/school/teacher-access.ts")
const staff = read("app/api/school/staff/route.ts")
const progress = read("app/api/teacher/progress/route.ts")
const student = read("app/api/student/teacher-links/route.ts")
const migration = read("supabase/migrations/20261118_school_staff_roles_and_teacher_links.sql")
const proxy = read("lib/supabase/proxy.ts")

for (const table of ["school_staff_roles","school_teacher_student_links","school_staff_audit_events"]) {
  assert.ok(migration.includes("alter table public."+table+" enable row level security"),table+" RLS required")
  assert.ok(migration.includes("revoke all on table public."+table+" from public, anon, authenticated"),table+" browser access must be denied")
}
assert.ok(migration.includes("school_teacher_link_role_fk"),"Teacher links must have a staff-role FK")
assert.ok(migration.includes("school_teacher_link_student_fk"),"Teacher links must have a same-school student FK")
assert.ok(migration.includes("on delete cascade"),"Links must be revoked on school removal")
assert.ok(scope.includes('school_staff_roles') && scope.includes('.eq("active", true)'),"Teacher role must be active")
assert.ok(scope.includes('school_seat_entitlements') && scope.includes('!seat?.active'),"Staff must retain active school membership")
assert.ok(scope.includes('canManageRoles: false'),"School Admin must not create global or additional staff admins")
assert.ok(staff.includes('if (!scope.canManageRoles)') || staff.includes('&& !scope.canManageRoles'),"Only school owner can grant staff roles")
assert.ok(staff.includes('email_confirmed_at'),"Unconfirmed emails must not receive staff access")
assert.ok(staff.includes('studentMembership.role === "owner"'),"School owner must not be linked as a student")
assert.ok(staff.includes('staffStudent?.active'),"Staff accounts must not be linked as students")
assert.ok(staff.includes('school_staff_audit_events'),"Grant/link actions must be auditable")
assert.ok(staff.includes('if (!role?.active)'),"Revoked teachers must not be linked")
assert.ok(progress.includes('loadStaffScope(admin,userId)'),"Progress endpoint must verify staff role each request")
assert.ok(progress.includes('school_teacher_student_links'),"Nonowner progress must be explicitly assigned")
assert.ok(progress.includes('scope.isOwner ? members : (links ?? [])'),"Only school owners may see all members")
assert.ok(progress.includes('!staffIds.has(id) && !ownerIds.has(id)'),"Staff and school owners are not student records")
assert.ok(progress.includes('school_seat_entitlements') && progress.includes('.eq("active",true)'),"Students must still be school members")
assert.ok(!progress.includes('transcript') && !progress.includes('overall_feedback') && !progress.includes('conversation'),"Teacher output must not expose private conversation content")
assert.ok(student.includes('.eq("student_user_id",userId)'),"Students may see only their own teacher links")
assert.ok(proxy.includes('"/teacher-dashboard"') && proxy.includes('"/school/teachers"'),"Staff pages require authenticated school routes")
assert.ok(fs.existsSync("app/teacher-dashboard/page.tsx"),"Teacher dashboard is required")
assert.ok(fs.existsSync("app/school/teachers/page.tsx"),"School owner management page is required")
assert.ok(fs.existsSync("app/student/teacher-links/page.tsx"),"Student transparency page is required")

console.log("PASS: school roles, same-school assignments, staff revocation, private progress and student link visibility are protected.")
